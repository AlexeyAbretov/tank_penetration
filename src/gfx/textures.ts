// Картинки поля и интерфейса. Спрайты сущностей рисуют сами классы:
// Tank (корпус, башня, снаряд, вспышка), AssaultInfantry, GunnerInfantry, PickupTruck, EnemyShot.
// Graphics рисует фигуры, bake сохраняет их как текстуру по строковому имени.

import Phaser from 'phaser';

// Рисует одноразовый холст и превращает его в текстуру с именем key.
// После этого холст удаляется: на сцене остаётся только сохранённая картинка.
export function bake(
  scene: Phaser.Scene,
  key: string, // имя, по которому текстуру потом берут спрайты
  width: number, // ширина картинки в пикселях
  height: number, // высота картинки в пикселях
  draw: (g: Phaser.GameObjects.Graphics) => void, // функция, которая собственно рисует
): void {
  // Graphics — невидимый «карандаш». Пока его не добавили бы в сцену насовсем, он нужен только чтобы снять текстуру.
  const g = scene.add.graphics();
  // Вызываем переданную функцию и отдаём ей этот карандаш.
  draw(g);
  // Снимок прямоугольника 0,0 — width,height кладётся в менеджер текстур под именем key.
  g.generateTexture(key, width, height);
  // Сам карандаш больше не нужен, иначе пустой объект останется в списке сцены.
  g.destroy();
}

// Генератор случайных чисел с фиксированным зерном.
// Обычный Math.random() каждый запуск даёт новый узор земли.
// Здесь зерно одно и то же, поэтому трещины и пятна всегда на своих местах.
// Формула — известный маленький алгоритм mulberry32. Нам важен результат: числа от 0 до 1.
function mulberry32(seed: number): () => number {
  // Возвращаем функцию без аргументов. Каждый её вызов выдаёт следующее число и меняет seed.
  return () => {
    // | 0 переводит число в 32-битное целое, как того ждёт алгоритм.
    seed |= 0;
    // 0x6d2b79f5 — константа алгоритма, «шаг» зерна. Не игровой цвет и не координата.
    seed = (seed + 0x6d2b79f5) | 0;
    // >>> — сдвиг битов вправо. ^ — XOR, побитовое «исключающее или». Так перемешивают биты зерна.
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    // Math.imul — умножение, которое не вылезает за 32 бита и не превращается в дробь.
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    // >>> 0 делает число беззнаковым. Деление на 2^32 даёт дробь от 0 включительно до 1 не включительно.
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Фон и элементы интерфейса. Картинки сущностей сцена просит у их классов.
export function createTextures(scene: Phaser.Scene): void {
  createBattlefield(scene); // фон поля
  createParticles(scene); // искра взрыва и уголёк
  createBanner(scene); // нижняя декоративная лента
  createHpFrame(scene); // рамка полоски здоровья базы
}

// Фон 1280×720: выжженная земля, пятна, трещины с огнём, искры.
function createBattlefield(scene: Phaser.Scene): void {
  // Зерно 0x7a12f3 выбрано один раз. Пока оно не меняется, картинка фона стабильна.
  bake(scene, 'battlefield', 1280, 720, (g) => {
    const rand = mulberry32(0x7a12f3);

    // Цвета ниже в формате 0xRRGGBB: RR красный, GG зелёный, BB синий, каждый байт от 00 до FF.
    // Самый тёмный подмалёвок на весь холст.
    g.fillStyle(0x2a0a08);
    // fillRect(x, y, ширина, высота). Ось X вправо, ось Y вниз, (0, 0) — левый верхний угол.
    g.fillRect(0, 0, 1280, 720);

    // Основное поле чуть светлее. Верхние 70 пикселей остаются тёмной «кромкой неба».
    g.fillStyle(0x4a140c);
    g.fillRect(0, 70, 1280, 650);

    // Большое тёплое пятно справа сверху, как зарево.
    g.fillStyle(0x5c1c10);
    // fillEllipse(центрX, центрY, ширина, высота).
    g.fillEllipse(900, 180, 900, 160);

    // 90 случайных пятен гари и светлой земли.
    for (let i = 0; i < 90; i += 1) {
      // rand() даёт 0..1, умножение растягивает это в диапазон пикселей.
      // 180 и 90 — отступ от левого и верхнего края, чтобы пятна не липли к рамке.
      const x = 180 + rand() * 1100;
      const y = 90 + rand() * 560;
      const w = 30 + rand() * 140;
      const h = 16 + rand() * 70;
      // Второй аргумент fillStyle — прозрачность от 0 до 1. Пятно полупрозрачное, фон просвечивает.
      // Тернарный оператор: если rand() > 0.5, берём тёмное пятно, иначе более рыжее.
      g.fillStyle(rand() > 0.5 ? 0x3a120c : 0x6a2414, 0.55 + rand() * 0.35);
      g.fillEllipse(x, y, w, h);
    }

    // 28 более тёмных вмятин поверх пятен.
    for (let i = 0; i < 28; i += 1) {
      const x = 260 + rand() * 980;
      const y = 110 + rand() * 500;
      const w = 18 + rand() * 70;
      const h = 10 + rand() * 28;
      g.fillStyle(0x2a0c08, 0.45);
      g.fillEllipse(x, y, w, h);
    }

    // Каждая трещина — список чисел парами: x, y, x, y, ... Ломаная из этих точек.
    const cracks = [
      [280, 160, 420, 210, 560, 190, 720, 250],
      [500, 320, 640, 360, 800, 340, 980, 400],
      [340, 480, 510, 510, 690, 490, 860, 540],
      [900, 140, 1040, 200, 1180, 170],
      [700, 80, 860, 120, 1020, 90, 1200, 130],
      [400, 380, 470, 430, 540, 410],
    ];

    for (const crack of cracks) {
      // Внутренняя функция рисует одну и ту же ломаную разной толщиной и цветом.
      // Четыре прохода подряд дают чёрную щель, красный жар, оранжевый и жёлтый блик.
      const draw = (width: number, color: number, alpha: number) => {
        // lineStyle задаёт карандаш для линий: толщина, цвет, прозрачность.
        g.lineStyle(width, color, alpha);
        g.beginPath();
        // Первая точка пары — старт линии.
        g.moveTo(crack[0], crack[1]);
        // Дальше шаг 2: каждый следующий x лежит на чётном индексе, y — сразу за ним.
        for (let i = 2; i < crack.length; i += 2) {
          g.lineTo(crack[i], crack[i + 1]);
        }
        g.strokePath();
      };
      draw(18, 0x1a0604, 0.95); // широкая почти чёрная борозда
      draw(12, 0xff3300, 0.95); // красная лава уже борозды
      draw(6, 0xffaa22, 1); // оранжевая сердцевина
      draw(2, 0xfff2aa, 0.9); // тонкий жёлтый блик
    }

    // Дымка огня у верхнего края, чтобы горизонт светился.
    g.fillStyle(0xff6600, 0.55);
    g.fillEllipse(1080, 90, 420, 70);
    g.fillStyle(0xff2200, 0.35);
    g.fillEllipse(640, 40, 900, 50);

    // 40 мелких угольков, разбросанных по полю.
    for (let i = 0; i < 40; i += 1) {
      g.fillStyle(0xc45a2a, 0.35 + rand() * 0.4);
      // fillCircle(центрX, центрY, радиус).
      g.fillCircle(200 + rand() * 1050, 100 + rand() * 530, 1 + rand() * 3);
    }
  });
}

// Две крошечные частицы: белая искра взрыва и оранжевый уголёк фона.
function createParticles(scene: Phaser.Scene): void {
  bake(scene, 'spark', 12, 12, (g) => {
    g.fillStyle(0xffffff);
    g.fillCircle(6, 6, 5);
  });
  bake(scene, 'ember', 8, 8, (g) => {
    g.fillStyle(0xff6622);
    g.fillCircle(4, 4, 3);
  });
}

// Нижняя лента интерфейса на всю ширину экрана.
function createBanner(scene: Phaser.Scene): void {
  bake(scene, 'banner', 1280, 86, (g) => {
    // Две красные полосы: тёмная подложка и более яркая середина.
    g.fillStyle(0x5a0c0c);
    g.fillRect(0, 8, 1280, 78);
    g.fillStyle(0x8a1810);
    g.fillRect(0, 14, 1280, 62);

    // Двойная золотая рамка. strokeRect(x, y, ширина, высота) обводит прямоугольник, не заливает.
    g.lineStyle(6, 0xc9a227, 1);
    g.strokeRect(8, 10, 1264, 70);
    g.lineStyle(2, 0xf0d56a, 1);
    g.strokeRect(16, 16, 1248, 58);

    // Золотые точки по верхнему и нижнему краю, шаг 48 пикселей.
    for (let x = 40; x < 1240; x += 48) {
      g.fillStyle(0xf0d56a);
      g.fillCircle(x, 12, 3);
      g.fillCircle(x, 78, 3);
    }
  });
}

// Рамка полоски HP базы. Сама красная заливка здоровья рисуется в сцене отдельным прямоугольником.
function createHpFrame(scene: Phaser.Scene): void {
  bake(scene, 'hp-frame', 280, 28, (g) => {
    // Тёмный жёлоб, в который ляжет полоска.
    g.fillStyle(0x1a1a1e);
    g.fillRoundedRect(0, 4, 280, 20, 8);
    g.lineStyle(2, 0x8a8680, 1);
    g.strokeRoundedRect(0, 4, 280, 20, 8);
    // Маленький треугольник-«стрелка» справа сверху, чисто украшение.
    g.fillStyle(0xa11a1a);
    g.fillTriangle(268, 0, 280, 14, 256, 14);
    // Круглый индикатор слева: тёмное кольцо и красная точка.
    g.fillStyle(0x6a1212);
    g.fillCircle(12, 14, 8);
    g.fillStyle(0xe04040);
    g.fillCircle(12, 14, 4);
  });
}
