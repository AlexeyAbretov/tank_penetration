// Все «ручки» баланса игры в одном объекте.
// Меняешь число здесь — меняется поведение, код сцен трогать не нужно.

// export: этот объект можно импортировать из других файлов.
// as const: TypeScript запоминает точные числа, а не просто «какой-то number».
export const GAME = {
  // Ширина игрового поля в пикселях. Совпадает с текстурой фона.
  width: 1280,
  // Высота игрового поля в пикселях.
  height: 720,
  // Координата X танка. Ноль — левый край, танк стоит почти у стены.
  tankX: 76,
  // Координата Y танка. Середина экрана по вертикали: 720 / 2 = 360.
  tankY: 360,
  // Пауза между выстрелами танка в миллисекундах (380 мс ≈ 2.6 выстрела в секунду).
  fireDelay: 380,
   // Скорость снаряда танка в пикселях в секунду.
   shellSpeed: 740,
  // Если враг, который идёт в рукопашную, дошёл до этой линии X — он бьёт базу.
  reachX: 115,
  // Радиус попадания по пехоте в пикселях: снаряд не обязан попасть пиксель в пиксель.
  shellHitRadius: 46,
  // Базовый урон одного снаряда. В магазине к нему прибавляется уровень урона.
  shellDamage: 1,
  // Каждый купленный уровень взрыва добавляет столько пикселей к радиусу.
  blastRadiusPerLevel: 1,
  // Здоровье базы (танка) в начале игры и после рестарта.
  baseHp: 100,
  // Здоровье пехоты за каждую волну: на волне 3 это 3 HP, если множитель равен 1.
  infantryHpPerWave: 1,
  // Ниже этой линии Y снаряды исчезают: там уже декоративный баннер, не поле боя.
  bannerY: 638,
  // Сколько врагов в первой волне.
  waveFirstCount: 6,
  // На каждую следующую волну врагов становится больше на это число.
  waveExtra: 4,
  // Пауза между появлениями врагов в первой волне, в миллисекундах.
  waveSpawnGap: 340,
  // Пауза не может стать меньше этого значения, даже на поздних волнах.
  waveMinGap: 150,
  // Сколько миллисекунд на экране висит надпись «ВОЛНА N», прежде чем враги пойдут.
  waveAnnounceMs: 1300,
  // Задержка перед первой волной после загрузки сцены.
  waveStartDelayMs: 700,
  // Цена первого улучшения (и взрыва, и урона).
  upgradeBaseCost: 3,
  // Каждая следующая покупка того же улучшения дороже на столько монет.
  upgradeCostStep: 2,
} as const;

// Цена улучшения, которое уже купили `level` раз.
// level 0 → 3 монеты, level 1 → 5, level 2 → 7 и так далее.
export function upgradeCost(level: number): number {
  return GAME.upgradeBaseCost + level * GAME.upgradeCostStep;
}
