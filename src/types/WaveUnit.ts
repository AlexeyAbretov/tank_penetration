// Юнит на поле с точки зрения менеджера волн: жив ли, где стоит, чем писать снимок.
// GameObject — чтобы сразу класть в группу Phaser; класс Infantry сюда не входит.

import type Phaser from 'phaser';

export type WaveUnit = Phaser.GameObjects.GameObject & {
  // true — дошёл до базы или доигрывает смерть; волну и сохранение не держит.
  reachedWall: boolean;
  x: number;
  y: number;
  hp: number;
  paceRank: number;
  // Монеты за убийство. Пропуск волны читает число, не зная класс пехоты.
  coinReward: number;
  // Очки за убийство. У обычного врага 10, у босса своё число.
  scoreReward: number;
  // Место в очереди волны. Сохранение возвращает босса на это место.
  slot: number;
  // Сколько солдат уже вышло из БТР. У остальных видов поля нет или оно ноль.
  routeMark?: number;
  // Включает скорость после появления или восстановления из сохранения.
  march(): void;
  // Смерть. Пропуск волны зовёт это, не зная класс пехоты.
  kill(): void;
};
